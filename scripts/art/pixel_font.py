UNKNOWN = "?"


def text_width(text: str, scale: int = 1) -> int:
    """Pixel width of a string at the given integer scale."""
    return max(0, len(text) * ADVANCE - 1) * scale


def draw_text(put, x: int, y: int, text: str, color: str, scale: int = 1) -> None:
    """
    Render `text` through a canvas `put(x, y, color)` callback.
    Only integer scaling is used so glyph pixels stay square and crisp.
    """
    cx = x
    for ch in text.upper():
        glyph = FONT5X7.get(ch, FONT5X7[UNKNOWN])
        for j, row in enumerate(glyph):
            for i, dot in enumerate(row):
                if dot == "#":
                    for sy in range(scale):
                        for sx in range(scale):
                            put(cx + i * scale + sx, y + j * scale + sy, color)
        cx += ADVANCE * scale
